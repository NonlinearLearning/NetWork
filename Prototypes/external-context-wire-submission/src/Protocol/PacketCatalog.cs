namespace Terraria.NetWork.Core.Protocol;

[Flags]
public enum PacketSupportFlags
{
    None = 0,
    InboundCodec = 1 << 0,
    OutboundCodec = 1 << 1,
    InboundFlow = 1 << 2,
    OpaqueCodec = 1 << 3
}

public sealed record PacketCatalogEntry(
    PacketType Type,
    PacketSupportFlags Support,
    string? CurrentServerTypeName = null,
    string? Notes = null)
{
    public byte MessageId => (byte)Type;
}

