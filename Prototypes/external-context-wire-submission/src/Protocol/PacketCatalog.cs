    public static PacketCatalogEntry Get(PacketType type) => All[(byte)type];

    public static PacketCatalogEntry Get(byte messageId) => All[messageId];

    private static PacketCatalogEntry Entry(
        PacketType type,
        PacketSupportFlags support = PacketSupportFlags.None,
        string? currentServerTypeName = null,
        string? notes = null)
    {
        return new PacketCatalogEntry(type, support, currentServerTypeName, notes);
    }

    private static PacketCatalogEntry Opaque(PacketType type, string currentServerTypeName, string? notes = null)
    {
        return Entry(
            type,
            PacketSupportFlags.InboundCodec | PacketSupportFlags.OutboundCodec | PacketSupportFlags.OpaqueCodec,
            currentServerTypeName,
            notes);
    }
